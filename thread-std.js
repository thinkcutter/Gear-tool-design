  // ASME B94.9 公制 M 牙型磨牙丝锥 D / DU 极限（MH 表 26、表 8b）：D 极限最大中径 = 基本中径 + 0.013n mm，最小 = 最大 − 表 26 公差；DU：最小 = 基本 − 0.013n
